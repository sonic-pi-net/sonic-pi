#!/usr/bin/env node
// Writes app/src/shortcut-defs.js: native Sonic Pi's keyboard-shortcut
// catalogue (MainWindow::shortcutDefs in app/gui/mainwindow.cpp), read out of
// its GUI source, so the web GUI's keymaps are native's and follow native when
// it changes. Each row keeps native's own notation (Meta+R, ShiftMeta+[ ...);
// app/src/shortcuts.js resolves it as native's resolveShortcut does.
//
//   node scripts/gen-shortcuts.mjs [path/to/sonic-pi]     # default: this repository
//
// A row inside `#if defined(Q_OS_MAC)` ... `#else` is native's per-platform
// variant of one command: only its secondary keys may differ. Anything it
// cannot read is an error, so a change in native's source is noticed rather
// than silently dropped.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SP = path.resolve(process.argv[2] ?? path.join(ROOT, "../.."));
const FILE = "app/gui/mainwindow.cpp";
const OUT = path.join(ROOT, "app/src/shortcut-defs.js");

const fail = (msg) => {
  console.error(`gen-shortcuts: ${msg}`);
  process.exit(1);
};

const src = fs.readFileSync(path.join(SP, FILE), "utf8");
const start = src.indexOf("MainWindow::shortcutDefs()");
const open = src.indexOf("defs = {", start);
const close = src.indexOf("return defs;", open);
if (start < 0 || open < 0 || close < 0) fail(`${FILE} has no \`MainWindow::shortcutDefs() { static const QList<ShortcutDef> defs = { ... }; return defs; }\``);

// a line's C string literals, in order, their escapes undone
const literals = (line) => [...line.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => m[1].replace(/\\(.)/g, "$1"));
const keyList = (s) => s.split(",").map((k) => k.trim()).filter(Boolean);

const rows = new Map();   // id → row, in native's order
let branch = null;        // null: every platform; "mac" or "other" inside #if defined(Q_OS_MAC)
for (const raw of src.slice(open + "defs = {".length, close).split("\n")) {
  const line = raw.trim();
  if (!line || line.startsWith("//") || line === "};") continue;
  if (line.startsWith("#")) {
    if (/^#if\s+defined\(Q_OS_MAC\)$/.test(line) && branch === null) branch = "mac";
    else if (line === "#else" && branch === "mac") branch = "other";
    else if (line === "#endif" && branch !== null) branch = null;
    else fail(`a preprocessor line it does not know in shortcutDefs(): ${line}`);
    continue;
  }
  const act = /&MainWindow::(\w+)/.exec(line)?.[1];
  const s = literals(line);
  if (!/^\{\s*"\w+",\s*QT_TR_NOOP\(".*"\),/.test(line) || !/\},?$/.test(line) || !act || (s.length !== 6 && s.length !== 7)) {
    fail(`a row it cannot read in shortcutDefs(): ${line}`);
  }
  const [id, desc, mac, win, emacs, group, secondary = ""] = s;
  const row = rows.get(id);
  if (!row) {
    const keys = keyList(secondary);
    rows.set(id, { id, desc, group, mac, win, emacs, act, secondary: branch ? { [branch]: keys } : { mac: keys, other: keys } });
    continue;
  }
  if (!branch || row.secondary[branch]) fail(`${id} is in shortcutDefs() twice`);
  for (const [k, v] of Object.entries({ desc, group, mac, win, emacs, act })) {
    if (row[k] !== v) fail(`${id}'s Mac and other variants differ in ${k}, not only in their secondary keys`);
  }
  row.secondary[branch] = keyList(secondary);
}
if (branch !== null) fail("shortcutDefs() has an #if without its #endif");
for (const row of rows.values()) {
  if (!row.secondary.mac || !row.secondary.other) fail(`${row.id} is only in one branch of an #if defined(Q_OS_MAC)`);
}
if (rows.size < 50) fail(`only ${rows.size} rows in shortcutDefs(): not the catalogue it was`);

const git = (...args) => { try { return execFileSync("git", ["-C", SP, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim(); } catch { return null; } };
const source = { sonic_pi: git("describe", "--tags", "--always"), commit: git("rev-parse", "HEAD"), file: FILE };

fs.writeFileSync(OUT, `// SPDX-License-Identifier: AGPL-3.0-or-later
// Generated by scripts/gen-shortcuts.mjs from native Sonic Pi's ${FILE}
// (MainWindow::shortcutDefs): regenerate rather than edit. Each row is one
// command: its id, description and menu group, its key in each of native's
// keymaps in native's notation (mac, win, emacs), the QAction it drives, and
// its undocumented secondary keys on a Mac and elsewhere.
export const SOURCE = ${JSON.stringify(source)};

export const SHORTCUT_DEFS = [
${[...rows.values()].map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${rows.size} shortcuts from ${source.sonic_pi ?? SP}`);
